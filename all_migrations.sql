-- Migration 008: Live Operations & Production Readiness
-- Adds: content versioning (published/draft/version/updated_by/published_at),
--       soft delete (deleted_at), audit log table, balance config table,
--       indexes, and published_at backfill for existing rows.
-- No breaking changes: all new columns are additive with safe defaults.

-- ============================================================
-- Versioning model:
--   * published BOOLEAN  â€” true = live row visible to players
--   * draft JSONB        â€” working copy snapshot (null = no draft)
--   * version INTEGER    â€” incremented on every draft save / publish
--   * updated_by TEXT    â€” admin UID who last touched the draft
--   * published_at       â€” timestamp of last publish
--   * deleted_at         â€” NULL = active; non-NULL = soft-deleted (hidden from players)
--
-- Workflow:
--   SaveDraft  â†’ set draft JSONB, version++, updated_by = admin
--   Publish    â†’ copy draft JSON to live columns, published=true, published_at=now, version++, clear draft
--   Preview    â†’ read draft JSON (or live columns if no draft)
--   SoftDelete â†’ deleted_at=now(), published=false (hidden from players)
--   Restore    â†’ deleted_at=NULL (and published=true if it was published before)
-- ============================================================

